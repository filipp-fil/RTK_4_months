# tech_cycle.py
# Неделя 1, пятница: базовый Python для инженерных задач.
# Скрипт выводит 10 шагов технологического цикла и проверяет номер каждого шага.

# --- 1. Список шагов технологического цикла (list of str) ---
# Это учебная последовательность для будущей роботизированной ячейки.
steps = [
    "1. Подача заготовки на входную позицию",
    "2. Проверка наличия детали датчиком",
    "3. Открытие захвата и подход к детали",
    "4. Захват детали",
    "5. Подтверждение захвата (датчик)",
    "6. Перенос детали к станку",
    "7. Установка детали в станок",
    "8. Условная обработка (5 секунд)",
    "9. Извлечение детали из станка",
    "10. Укладка детали на выходную позицию",
]

# --- 2. Ожидаемое количество шагов (int) ---
EXPECTED_STEPS = 10

# --- 3. Проверка общего количества шагов ---
# Сравниваем фактическое число шагов с ожидаемым.
actual_steps = len(steps)
print(f"Всего шагов в цикле: {actual_steps} (ожидается {EXPECTED_STEPS})")

if actual_steps != EXPECTED_STEPS:
    # Если количество не совпало — сообщаем и завершаем с ошибкой.
    print("ОШИБКА: количество шагов не совпадает с ожидаемым.")
    raise SystemExit(1)
else:
    print("Количество шагов корректно.\n")

# --- 4. Вывод шагов и проверка номера каждого шага (цикл for) ---
# enumerate даёт и индекс (с 0), и сам элемент. Номер шага = индекс + 1.
for index, step_text in enumerate(steps):
    step_number = index + 1  # номер шага: 1..10

    # Проверяем, что номер шага в допустимом диапазоне 1..EXPECTED_STEPS.
    if 1 <= step_number <= EXPECTED_STEPS:
        status = "OK"
    else:
        status = "ОШИБКА: номер вне диапазона"

    # Выводим шаг и результат проверки.
    print(f"[{status}] Шаг {step_number}: {step_text}")

print("\nЦикл выведен и проверен.")